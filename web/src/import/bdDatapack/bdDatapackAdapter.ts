const decoder = new TextDecoder();
const TICKS_PER_BD_FRAME = 2;
const MAX_ARCHIVE_ENTRY_BYTES = 64 * 1024 * 1024;
const CREATE_PATH = /^data\/([^/]+)\/functions?\/_\/create\.mcfunction$/;
const KEYFRAME_PATH = /^data\/([^/]+)\/functions?\/k\/([^/]+)\/keyframe_(\d+)\.mcfunction$/;
const OWNED_DISPLAY_FIELDS = new Set([
  "id", "Tags", "Passengers", "transformation", "interpolation_duration", "start_interpolation",
  "item", "item_display", "block_state", "text",
]);

interface BdDatapackArchive {
  files: Map<string, string>;
  namespace: string;
  createPath: string;
}

interface ImportedDisplays {
  nodes: Record<string, ImportedNode>;
  nodeIdsByTag: Map<string, string>;
  payloadByNodeId: Map<string, string>;
}

export const bdDatapackAdapter: ImportAdapter<ImportedProject> = {
  id: "bd_datapack",
  label: "BD Engine datapack",
  extensions: ["zip"],

  probe(input: ImportInput): ProbeResult {
    if (!hasZipHeader(input.bytes)) return { confidence: 0, reason: "not a ZIP archive" };
    try {
      readArchive(input);
      return { confidence: 100, reason: "contains a BD Engine create function and animation keyframes" };
    } catch {
      return { confidence: 0, reason: "not a BD Engine datapack" };
    }
  },

  async import(input: ImportInput): Promise<ImportedProject> {
    const archive = readArchive(input);
    const createFunction = archive.files.get(archive.createPath)!;
    const displays = importDisplays(createFunction, archive.namespace);
    const diagnostics: ImportedProject["diagnostics"] = [];
    const animations = importAnimations(archive, displays, diagnostics);
    if (animations.length === 0) throw new Error("BD Engine datapack does not contain animation keyframes.");
    const name = prettify(archive.namespace);
    return {
      source: "bd_datapack",
      sourceName: input.name,
      suggestedMetadata: { name, description: `${name} emote.` },
      suggestedPlayer: createDefaultPlayerBehavior(),
      suggestedNamespace: archive.namespace,
      nodes: displays.nodes,
      animations,
      diagnostics,
      resources: new Map(),
    };
  },
};

function readArchive(input: ImportInput): BdDatapackArchive {
  return cachedInputValue(input, "bd_datapack_zip", () => {
    if (!hasZipHeader(input.bytes)) throw new Error("BD Engine datapack is not a ZIP archive.");
    const files = new Map<string, string>();
    let entries: Record<string, Uint8Array>;
    try {
      entries = unzipSync(input.bytes, {
        filter: (entry) => entry.originalSize <= MAX_ARCHIVE_ENTRY_BYTES
          && (entry.name === "pack.mcmeta" || CREATE_PATH.test(entry.name) || KEYFRAME_PATH.test(entry.name)),
      });
    } catch (error) {
      throw new Error("BD Engine datapack ZIP could not be read.", { cause: error });
    }
    for (const [path, bytes] of Object.entries(entries)) files.set(path.replaceAll("\\", "/"), decoder.decode(bytes));
    const creates = [...files.keys()].flatMap((path) => {
      const match = CREATE_PATH.exec(path);
      return match ? [{ path, namespace: match[1] }] : [];
    });
    if (creates.length !== 1) throw new Error(`BD Engine datapack must contain exactly one create function; found ${creates.length}.`);
    const create = creates[0];
    if (!files.get(create.path)?.includes("Project created via BDEngine")) {
      throw new Error("Datapack create function was not generated by BD Engine.");
    }
    if (![...files.keys()].some((path) => KEYFRAME_PATH.test(path))) {
      throw new Error("BD Engine datapack does not contain keyframes.");
    }
    return { files, namespace: create.namespace, createPath: create.path };
  });
}

function hasZipHeader(bytes: Uint8Array): boolean {
  return bytes.length >= 4 && bytes[0] === 0x50 && bytes[1] === 0x4b
    && ((bytes[2] === 0x03 && bytes[3] === 0x04) || (bytes[2] === 0x05 && bytes[3] === 0x06));
}

function importDisplays(createFunction: string, namespace: string): ImportedDisplays {
  const found: { index: number; tag: string; node: ImportedNode; payload: string }[] = [];
  const entityStart = /\{\s*id\s*:\s*["'](?:minecraft:)?(item_display|block_display|text_display)["']/g;
  for (const match of createFunction.matchAll(entityStart)) {
    const start = match.index!;
    const end = findMatchingSnbtDelimiter(createFunction, start, "{", "}");
    const compound = createFunction.slice(start, end + 1);
    const tag = readStringList(readSnbtRawField(compound, "Tags"))
      .find((value) => new RegExp(`^${escapeRegExp(namespace)}_(\\d+)$`).test(value));
    if (!tag) continue;
    const index = Number(new RegExp(`^${escapeRegExp(namespace)}_(\\d+)$`).exec(tag)![1]);
    const node = importDisplay(`display_${index}`, match[1], compound);
    found.push({ index, tag, node, payload: readDisplayPayloadUpdate(node, compound)! });
  }
  found.sort((first, second) => first.index - second.index);
  if (found.length === 0) throw new Error("BD Engine datapack create function does not contain display nodes.");
  const tags = new Set<string>();
  for (const display of found) {
    if (tags.has(display.tag)) throw new Error(`BD Engine datapack contains duplicate display tag ${display.tag}.`);
    tags.add(display.tag);
  }
  const nodes = Object.fromEntries(found.map((display) => [display.node.id, display.node]));
  const nodeIdsByTag = new Map(found.map((display) => [display.tag, display.node.id]));
  const payloadByNodeId = new Map(found.map((display) => [display.node.id, display.payload]));
  return {
    nodes,
    nodeIdsByTag,
    payloadByNodeId,
  };
}

function importDisplay(id: string, type: string, compound: string): ImportedNode {
  const defaultMatrix = readMatrix(readSnbtRawField(compound, "transformation"), `${id} create transformation`);
  const entityNbt = omitSnbtFields(compound, OWNED_DISPLAY_FIELDS);
  const common = { id, defaultMatrix, visible: true, skinAssignmentGroup: id, ...(entityNbt ? { entityNbt } : {}) };
  if (type === "item_display") {
    const item = readSnbtRawField(compound, "item");
    if (!item) throw new Error(`BD Engine datapack node ${id} does not contain an item.`);
    return {
      ...common,
      type: "item_display",
      itemStack: readItemStack(item),
      itemDisplay: readSnbtStringField(compound, "item_display") ?? readBareField(compound, "item_display") ?? "none",
    };
  }
  if (type === "block_display") {
    const blockState = readSnbtRawField(compound, "block_state");
    if (!blockState) throw new Error(`BD Engine datapack node ${id} does not contain block_state.`);
    return { ...common, type: "block_display", blockState: readBlockState(blockState) };
  }
  const text = readSnbtStringField(compound, "text") ?? readBareField(compound, "text") ?? "";
  return { ...common, type: "text_display", text: parseText(text) };
}

function importAnimations(
  archive: BdDatapackArchive,
  displays: ImportedDisplays,
  diagnostics: ImportedProject["diagnostics"],
): ImportedAnimation[] {
  const grouped = new Map<string, { index: number; path: string; content: string }[]>();
  for (const [path, content] of archive.files) {
    const match = KEYFRAME_PATH.exec(path);
    if (!match || match[1] !== archive.namespace) continue;
    const frames = grouped.get(match[2]) ?? [];
    frames.push({ index: Number(match[3]), path, content });
    grouped.set(match[2], frames);
  }
  let droppedCamera = false;
  const animations = [...grouped.entries()].sort(([first], [second]) => first.localeCompare(second)).map(([animationName, frames]) => {
    frames.sort((first, second) => first.index - second.index);
    frames.forEach((frame, expected) => {
      if (frame.index !== expected) throw new Error(`BD Engine animation ${animationName} is missing keyframe_${expected}.mcfunction.`);
    });
    const durationTicks = requireAnimationDurationTicks(frames.length * TICKS_PER_BD_FRAME, `${animationName} duration`);
    const tracks: Record<string, ImportedNodeTrack> = Object.fromEntries(
      Object.keys(displays.nodes).map((id) => [id, { transforms: [], visibility: [], nbt: [] }]),
    );
    const currentPayloadByTag = new Map([...displays.nodeIdsByTag].map(([tag, nodeId]) => [tag, displays.payloadByNodeId.get(nodeId)!]));
    for (const frame of frames) {
      const lines = frame.content.split(/\r?\n/).map((value) => value.trim()).filter(Boolean);
      for (const line of lines) {
        if (line.startsWith("#") || line.startsWith("schedule function ")) continue;
        if (line.includes(`tag=${archive.namespace}_camera`)) {
          droppedCamera = true;
          continue;
        }
        const merge = /^data merge entity @e\[([^\]]+)]\s+(\{.*})$/.exec(line);
        if (!merge) throw new Error(`Unsupported command in ${frame.path}: ${line}`);
        const tag = /(?:^|,)tag=([^,\]]+)/.exec(merge[1])?.[1];
        const baseNodeId = tag ? displays.nodeIdsByTag.get(tag) : undefined;
        if (!tag || !baseNodeId) throw new Error(`Keyframe ${frame.path} targets an unknown display tag: ${tag ?? "<missing>"}`);
        validateDisplayMerge(displays.nodes[baseNodeId], merge[2], frame.path);
        const payloadUpdate = readDisplayPayloadUpdate(displays.nodes[baseNodeId], merge[2]);
        if (!payloadUpdate) continue;
        const mergedPayload = mergeSnbtValue(currentPayloadByTag.get(tag)!, payloadUpdate);
        setNbtFrame(
          tracks[baseNodeId],
          frame.index * TICKS_PER_BD_FRAME,
          displays.nodes[baseNodeId],
          displays.payloadByNodeId.get(baseNodeId)!,
          mergedPayload,
        );
        currentPayloadByTag.set(tag, mergedPayload);
      }
      for (const line of lines) {
        if (line.startsWith("#") || line.startsWith("schedule function ") || line.includes(`tag=${archive.namespace}_camera`)) continue;
        const merge = /^data merge entity @e\[([^\]]+)]\s+(\{.*})$/.exec(line)!;
        const matrix = readSnbtRawField(merge[2], "transformation");
        if (!matrix) continue;
        const tag = /(?:^|,)tag=([^,\]]+)/.exec(merge[1])?.[1];
        const nodeId = tag ? displays.nodeIdsByTag.get(tag) : undefined;
        if (!nodeId) throw new Error(`Keyframe ${frame.path} targets an unknown display tag: ${tag ?? "<missing>"}`);
        const duration = readIntegerField(merge[2], "interpolation_duration", 0);
        tracks[nodeId].transforms.push({
          tick: frame.index * TICKS_PER_BD_FRAME,
          matrix: readMatrix(matrix, `${frame.path} ${nodeId} transformation`),
          interpolation: duration === 0 ? { type: "step" } : { type: "linear", durationTicks: duration },
        });
      }
    }
    return {
      id: sanitizeResourcePath(animationName, "default"),
      name: prettify(animationName),
      durationTicks,
      playbackMode: "loop" as const,
      loopDelayTicks: 0,
      tracks,
      events: { start: [], timeline: [], loop: [], stop: [] },
    };
  });
  if (droppedCamera) diagnostics.push({
    severity: "warning",
    code: "bd_datapack_camera_ignored",
    message: "BD Engine camera movement is not part of the emote format and was ignored.",
    sourcePath: "data/*/function/k/*/keyframe_*.mcfunction",
  });
  return animations;
}

function validateDisplayMerge(node: ImportedNode, compound: string, path: string): void {
  const allowed = new Set(["transformation", "interpolation_duration", "start_interpolation"]);
  if (node.type === "item_display") allowed.add("item");
  else if (node.type === "block_display") allowed.add("block_state");
  else if (node.type === "text_display") allowed.add("text");
  const unsupported = parseSnbtCompound(compound).find((field) => !allowed.has(field.name));
  if (unsupported) throw new Error(`Unsupported display data field ${unsupported.name} in ${path}.`);
}

function readDisplayPayloadUpdate(node: ImportedNode, compound: string): string | null {
  if (node.type === "item_display") return readSnbtRawField(compound, "item");
  if (node.type === "block_display") return readSnbtRawField(compound, "block_state");
  if (node.type === "text_display") return readSnbtRawField(compound, "text");
  return null;
}

function setNbtFrame(
  track: ImportedNodeTrack,
  tick: number,
  node: ImportedNode,
  initialPayload: string,
  payload: string,
): void {
  if (track.nbt.length === 0) track.nbt.push({ tick: 0, value: readDisplayNbt(displayPayloadNbt(node, initialPayload)) });
  const frame = { tick, value: readDisplayNbt(displayPayloadNbt(node, payload)) };
  if (track.nbt.at(-1)!.tick === tick) track.nbt[track.nbt.length - 1] = frame;
  else track.nbt.push(frame);
}

function displayPayloadNbt(node: ImportedNode, payload: string): string {
  if (node.type === "item_display") return serializeSnbtCompound([["item", payload]]);
  if (node.type === "block_display") return serializeSnbtCompound([["block_state", payload]]);
  if (node.type === "text_display") return serializeSnbtCompound([["text", payload]]);
  throw new Error(`Node ${node.id} is not a display.`);
}

function mergeSnbtValue(current: string, update: string): string {
  if (!current.startsWith("{") || !current.endsWith("}") || !update.startsWith("{") || !update.endsWith("}")) return update;
  const fields = new Map(parseSnbtCompound(current).map((field) => [field.name, field.value]));
  for (const field of parseSnbtCompound(update)) {
    const previous = fields.get(field.name);
    fields.set(field.name, previous ? mergeSnbtValue(previous, field.value) : field.value);
  }
  return serializeSnbtCompound(fields);
}

function readMatrix(raw: string | null, label: string): Matrix16 {
  if (!raw?.startsWith("[") || !raw.endsWith("]")) throw new Error(`${label} must be an SNBT list.`);
  return asMatrix16(splitSnbtTopLevel(raw.slice(1, -1)).map((value) => {
    const parsed = Number(value.replace(/[bBsSlLfFdD]$/, ""));
    if (!Number.isFinite(parsed)) throw new Error(`${label} contains an invalid number: ${value}`);
    return parsed;
  }), label);
}

function readStringList(raw: string | null): string[] {
  if (!raw?.startsWith("[") || !raw.endsWith("]")) return [];
  return splitSnbtTopLevel(raw.slice(1, -1)).flatMap((value) => {
    try {
      const parsed = JSON.parse(value) as unknown;
      return typeof parsed === "string" ? [parsed] : [];
    } catch {
      return value.startsWith("'") && value.endsWith("'") ? [value.slice(1, -1)] : [];
    }
  });
}

function readBareField(compound: string, name: string): string | null {
  const raw = readSnbtRawField(compound, name);
  return raw && /^[A-Za-z0-9._+-]+$/.test(raw) ? raw : null;
}

function readIntegerField(compound: string, name: string, fallback: number): number {
  const raw = readSnbtRawField(compound, name);
  if (raw == null) return fallback;
  const value = Number(raw.replace(/[bBsSlL]$/, ""));
  if (!Number.isInteger(value) || value < 0) throw new Error(`${name} must be a non-negative integer.`);
  return value;
}

function parseText(value: string): unknown {
  try { return JSON.parse(value) as unknown; } catch { return { text: value }; }
}

function prettify(value: string): string {
  return value.replaceAll("_", " ").replace(/\b\w/g, (character) => character.toUpperCase());
}

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}
